CREATE TABLE IF NOT EXISTS payfast_orders (
 id CHAR(32) PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 plan VARCHAR(20) NOT NULL,
 amount_cents INT UNSIGNED NOT NULL,
 mode VARCHAR(12) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending',
 payment_id VARCHAR(80) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_pf_order_user (user_id,created_at),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payfast_subscriptions (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 order_id CHAR(32) NOT NULL,
 token VARCHAR(100) NULL,
 plan VARCHAR(20) NOT NULL,
 status VARCHAR(24) NOT NULL,
 mode VARCHAR(12) NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY (order_id) REFERENCES payfast_orders(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payfast_notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 payment_id VARCHAR(80) NOT NULL,
 payment_status VARCHAR(32) NOT NULL,
 order_id CHAR(32) NOT NULL,
 received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_payfast_payment_state (payment_id,payment_status),
 FOREIGN KEY (order_id) REFERENCES payfast_orders(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payfast_invoices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 invoice_number VARCHAR(70) NOT NULL UNIQUE,
 user_id BIGINT UNSIGNED NOT NULL,
 payment_id VARCHAR(80) NOT NULL UNIQUE,
 order_id CHAR(32) NOT NULL,
 amount_cents INT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'ZAR',
 status VARCHAR(20) NOT NULL DEFAULT 'paid',
 issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_pf_invoice_user (user_id,issued_at),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY (order_id) REFERENCES payfast_orders(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;